const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {makeHarness}=require('./helpers/dom-harness.cjs');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const nav=fs.readFileSync(path.join(root,'server/z5-ingame.js'),'utf8');
const bridge="globalThis.rx5TrialFixture={\n setup:()=>{phase='playing';mode='solo';paused=false;pl.alive=true;pl.x=0;pl.z=0;pl.yaw=0;obstacles.length=0;rx2Covers=[];rx2Gadgets=[];bots.length=0;rx2GadgetStock=3;rx2GadgetReadyAt=0;const b=spawnBot(0);b.x=0;b.z=-9;b.hp=100;b.alive=true;bots.push(b);},\n gadget:type=>rx2Gadget(type), stock:()=>rx2GadgetStock, bot:()=>bots[0],\n botBehavior:(dt,now)=>rx2BotBehavior(bots[0],dt,now),\n shields:()=>rx2Covers.filter(c=>c.rx5Portable),\n coverRay:()=>rx2CoverRay(0,1.5,0,0,0,-1),tick:now=>rx2Tick(.016,now),\n setMode:next=>mode=next,\n blueprint:(name,gun)=>{rx5BlueprintChoice=name;return rx5BlueprintWeapon(weapons[gun],gun);},\n unlock:(gun,hits,kills)=>{rx5Mastery.hits[gun]=hits;rx5Mastery.kills[gun]=kills;},\n base:gun=>weapons[gun],\n lesson:lesson=>{phase='playing';mode='training';rx5AcademyActive=true;rx5AcademyLesson=lesson;rx2AfterStart('training');return {count:bots.length,weapon:pl.weapon,time:gameSeconds};},\n legacy:()=>{phase='playing';mode='training';rx5AcademyActive=false;rx2AfterStart('training');return gameSeconds;},\n medal:()=>{pl.hits=60;pl.shots=100;rx2Kills=18;rx5AcademyFinish();return rx5AcademyMedals[rx5AcademyLesson];}\n};";
test('new tactical UI and combat scripts are present and parse',()=>{
 assert.match(html,/function rx5AcademyFinish/);
 assert.match(html,/rx5EmpUntil/);
 assert.match(html,/rx5Portable:true/);
 assert.match(nav,/Training Academy/);
 assert.match(nav,/EMP grenade/);
 assert.doesNotThrow(()=>new vm.Script(nav,{filename:'z5-ingame.js'}));
});
test('EMP disables nearby solo bots without multiplayer authority',()=>{
 const h=makeHarness({},'2026-11-21T13:00:00Z',null,bridge),f=h.ctx.rx5TrialFixture;
 f.setup();h.perf(1000);
 assert.equal(f.gadget('emp'),true);
 assert.ok(f.bot().rx5EmpUntil>1);
 assert.equal(f.stock(),2);
 const x=f.bot().x;
 assert.equal(f.botBehavior(.1,1.2),true);
 assert.equal(f.bot().x,x);
 f.setMode('host');
 assert.equal(f.gadget('emp'),false);
 assert.equal(f.stock(),2);
});
test('portable shield blocks raycasts, expires and is denied in multiplayer',()=>{
 const h=makeHarness({},'2026-11-21T13:00:00Z',null,bridge),f=h.ctx.rx5TrialFixture;
 f.setup();h.perf(1000);
 assert.equal(f.gadget('shield'),true);
 assert.equal(f.shields().length,1);
 assert.equal(f.shields()[0].hp,165);
 assert.ok(f.coverRay()<7);
 f.setMode('host');h.perf(7000);
 assert.equal(f.gadget('shield'),false);
 assert.equal(f.shields().length,1);
 f.setMode('solo');h.perf(15000);f.tick(15);
 assert.equal(f.shields().length,0);
});
test('blueprint modifiers change real offline gun stats, never multiplayer',()=>{
 const h=makeHarness({},'2026-11-21T13:00:00Z',null,bridge),f=h.ctx.rx5TrialFixture;
 f.setup();f.unlock(0,90,25);
 const base=f.base(0),steady=f.blueprint('steady',0);
 assert.ok(steady.spread<base.spread);
 assert.ok(steady.cadence>base.cadence);
 const impact=f.blueprint('impact',0);
 assert.ok(impact.damage>base.damage);
 f.setMode('host');
 assert.equal(f.blueprint('impact',0).damage,base.damage);
 f.setMode('solo');f.unlock(0,0,0);
 assert.equal(f.blueprint('impact',0).damage,base.damage);
});
test('academy lessons use actual weapons, save medals, and retain original training',()=>{
 const h=makeHarness({},'2026-11-21T13:00:00Z',null,bridge),f=h.ctx.rx5TrialFixture;
 f.setup();
 const tracking=f.lesson('tracking');
 assert.equal(tracking.weapon,3);
 assert.equal(tracking.time,90);
 assert.equal(tracking.count,7);
 const medal=f.medal();
 assert.equal(medal.tier,3);
 assert.equal(medal.kills,18);
 assert.equal(f.legacy(),240);
 assert.ok(h.ui.querySelector('#rx5AcademyDialog'));
 assert.equal(typeof h.ctx.RXZ5Academy.open,'function');
 assert.ok(h.ctx.RXZ5Gear.options.includes('shield'));
});